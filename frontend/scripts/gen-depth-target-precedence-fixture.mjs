// NF-C7b — record what the TYPESCRIPT resolver answers for every shared precedence case.
//
// ══ WHY THIS EXISTS ═══════════════════════════════════════════════════════════════════════════
// Depth-target precedence (league → account → none) has to hold in two places: the browser, which
// ranks the web draft surfaces, and the API Lambda, which ranks the live draft for the Chrome
// extension. Two implementations of one rule are two rule sets (E9.61) — and this repo has already
// paid for that twice: a player's name upper-cased by two different passes, and the two draft
// engines this same story's sibling found silently two fixes apart.
//
// So the rule is stated ONCE, in `betting_ml/tests/fixtures/nf_c7b_depth_target_precedence.json`,
// and BOTH sides are held to it. Python asserts against the fixture directly. TypeScript cannot be
// imported from pytest, so this script runs the real shipped resolver over the same cases and
// records its answers; `test_nf_c7b_depth_target_settings.py` asserts they match the fixture too.
//
// ⚠️ REAL RESOLVER OUTPUT, NEVER HAND-WRITTEN (NF-C0e). Regenerate — do not edit — in the SAME
// commit as any deliberate change to the rule:
//
//     node --experimental-strip-types frontend/scripts/gen-depth-target-precedence-fixture.mjs
//
// (Node >= 22.6 for `--experimental-strip-types`. Not on the CI path — the committed output is —
// so an unavailable node cannot silently turn the guard green.)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveDepthTargets } from '../lib/depth-targets.ts'

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const SRC = path.join(REPO, 'betting_ml/tests/fixtures/nf_c7b_depth_target_precedence.json')
const OUT = path.join(REPO, 'betting_ml/tests/fixtures/nf_c7b_depth_target_precedence_ts.json')

const { cases } = JSON.parse(fs.readFileSync(SRC, 'utf8'))

const answers = cases.map((c) => {
  // ⚠️ `local` is deliberately left UNSET. It is a client-only fourth level (an ad-hoc value for a
  // draft against a preset format, where there is no record to write to) and the server has no
  // equivalent, so the shared cases pin the two levels both sides actually have.
  const { targets, source } = resolveDepthTargets({ league: c.league, account: c.account })
  return { name: c.name, targets, source }
})

fs.writeFileSync(
  OUT,
  JSON.stringify(
    {
      _note:
        'Generated by frontend/scripts/gen-depth-target-precedence-fixture.mjs from the SHIPPED ' +
        'lib/depth-targets.ts resolver. Do not edit by hand — regenerate.',
      answers,
    },
    null,
    2,
  ) + '\n',
)
console.log(`wrote ${OUT}: ${answers.length} answers`)
