/**
 * Resolve a POSTed ESPN paste to the preview the server would answer with.
 *
 * ⭐ KEYED ON THE PASTE'S OWN `(id, seasonId)`, not on anything the spec configures. That is what
 * makes "pasting league A's blob shows league A's settings" an assertion rather than an assumption:
 * a harness that returned a canned preview would pass just as happily if the app posted the wrong
 * payload, sent it to the wrong endpoint, or corrupted it in `pruneEspnPayload` on the way out.
 *
 * Returns `undefined` for anything unrecognised, which the caller turns into the server's 422 —
 * the honest answer, and the one that makes the "a bad paste says why" case reachable.
 */
function espnPreviewForPaste(posted: string): unknown | undefined {
  let doc: any
  try {
    doc = JSON.parse(posted)
  } catch {
    return undefined
  }
  const leagueId = doc?.id == null ? null : String(doc.id)
  const seasonId = doc?.seasonId == null ? null : String(doc.seasonId)
  if (!leagueId || !seasonId) return undefined
  const known = Object.values(ESPN_REAL_PASTES).some(
    (p) => p.leagueId === leagueId && p.seasonId === seasonId,
  )
  if (!known) return undefined
  return FIXTURES.importEspnPreview(leagueId, seasonId)
}

