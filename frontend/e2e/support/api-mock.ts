/**
 * ⭐ E9.64 — THE IMPORT PREVIEW: step 2 of the importer, "Review what we read".
 *
 * ══ WHY THIS IS SYNTHESISED AND WHY THAT IS THE RIGHT CALL HERE ═══════════════════════════════
 *
 * The README's rule is ⛔ do not hand-write a fixture, because a hand-written one encodes the
 * assumption under test. There is no capture to take: `/fantasy/import/sleeper/preview` requires an
 * authenticated caller AND a real Sleeper league, so nothing anonymous can produce one — the same
 * position `build-entitled-fixture.mjs` and the track-record claim builder were in, and this follows
 * their precedent: derive everything that CAN be real, and say plainly what cannot.
 *
 *   · `config` IS the real captured league (`fantasy-nfl-my-teams.json`) — its scoring, its roster
 *     shape, its team count. That is the part the review screen reads out, so it is the part that
 *     had to be real.
 *   · `teams` are built from the real board, so the roster names resolve through the same
 *     `name|pos` join the app uses.
 *   · `warnings` / `unmapped_scoring_keys` are SYNTHETIC, and unavoidably so: a warning list has to
 *     be NON-EMPTY for "the things we could not read are shown before you save" to mean anything,
 *     and no anonymous capture can supply one. ⚠️ That is not a hole in the assertion, because the
 *     property under test is that whatever the SERVER sends is rendered VERBATIM — the component's
 *     own comment ("an import that quietly loses a rule is the failure this whole surface guards").
 *     The wording being ours is exactly why the spec can check it word for word.
 */
export const E2E_IMPORT_WARNING =
  "Your league scores a bonus for a 40+ yard reception that we record but do not project."

/** A scoring key we carry through under the platform's own name without projecting it. */
export const E2E_IMPORT_UNMAPPED_KEY = "rec_40p_bonus"

/** Two teams off the real board. Neither is flagged `is_owner` — Sleeper cannot tell us which team
 *  is the caller's, which is precisely why the review screen makes the user pick one (NF-C6). */
function previewTeams(): unknown[] {
  const players = FIXTURES.projectionsEntitled().players as any[]
  const take = (from: number, count: number) =>
    players.slice(from, from + count).map((p) => ({
      player_key: `e2e-${p.id}`,
      name: p.name,
      position: p.pos,
      team: p.team,
      starter: true,
    }))
  return [
    { team_key: "e2e-team-1", name: "Credence FC", owner: "e2e-tester", is_owner: false, players: take(0, 4) },
    { team_key: "e2e-team-2", name: "Rivals United", owner: "someone-else", is_owner: false, players: take(4, 4) },
  ]
}

function importPreviewFor(sourceLeagueId: string): unknown {
  const base = FIXTURES.myTeams().leagues[0] as any
  // The league CONFIG only — never the saved-league envelope. A preview describes what the platform
  // says, and carrying `league_id` through here would let a spec pass while the importer treated an
  // un-saved preview as an already-saved league.
  const { name, n_teams, ppr, superflex, scoring, roster, sport, format_version } = base
  return {
    platform: "sleeper",
    source_league_id: sourceLeagueId,
    season: "2026",
    config: {
      name,
      n_teams,
      ppr,
      superflex,
      // ⚠️ A CAPTURED TERM IS AN ORDINARY `per_stat` RULE WITH NO PROJECTION BEHIND IT — that is the
      // whole mechanism, and it took two wrong guesses to land on. `resolveScoring` builds its term
      // list from `per_stat` ALONE and grades each key `applied` or `captured` by whether
      // `STAT_FIELD` knows it; `capturedRules` is carried on the report but never becomes a term,
      // and `unmapped_scoring_keys` only supplies display LABELS. So a mock that set either of
      // those instead (both read as the obvious place) would render the disclosure nowhere while
      // looking entirely reasonable — and a spec asserting on it would be asserting on a screen the
      // user never sees. `captured_rules` is kept alongside because that is where a SAVED league
      // stores the same fact.
      scoring: {
        ...scoring,
        per_stat: { ...scoring.per_stat, [E2E_IMPORT_UNMAPPED_KEY]: 1.5 },
      },
      roster,
      sport,
      format_version,
      captured_rules: { [E2E_IMPORT_UNMAPPED_KEY]: 1.5 },
    },
    teams: previewTeams(),
    draft: null,
    warnings: [E2E_IMPORT_WARNING],
    unmapped_scoring_keys: [E2E_IMPORT_UNMAPPED_KEY],
  }
}

/**
 * G100-C1 — the PER-CALLER saved-league reads.
 *
 * ⚠️ Kept OUT of `payloadFor` on purpose. That function is a pure map from (path, entitlement) to a
 * fixture, which is exactly right for the generic surfaces — their whole invariant is that the
 * payload does NOT depend on the caller. These two do. Threading a saved-league count through
 * `payloadFor` would blur the one distinction the harness exists to model, so the per-caller reads
 * get their own resolver and the shape of the code states which half of the tier each path is in.
 */
function personalPayloadFor(
  pathname: string,
  leagues: NonNullable<MockOptions["leagues"]>,
): unknown | undefined {
  // 🔒 NF-EPIC 1 — the league board is scored SERVER-SIDE now (the raw stat line it is scored from
  // became paid). The harness computes it with the SAME `buildBoard` the browser used to run, off
  // the entitled projections fixture, so the delta this screen exists to show stays REAL. Returning
  // the generic board here instead would make every riser/faller assertion pass against a board
  // that never moved — the vacuous-fixture shape this file already guards against elsewhere.
  if (pathname === "/fantasy/nfl/league-board") {
    const league = FIXTURES.myTeams().leagues[0]
    if (!league || leagues === "none") return undefined
    const built = leagueBoardBuild()
    return {
      season: 2026,
      league,
      board: {
        players: built.players,
        replacement: built.replacement,
        started: built.started,
        coverage: built.coverage,
      },
      roster: matchRosterToBoard(league.imported_roster ?? [], built.players),
    }
  }
  if (pathname !== "/fantasy/nfl/my-teams" && pathname !== "/fantasy/leagues") return undefined

  const base = FIXTURES.myTeams()
  const one = base.leagues[0]
  // NF-EPIC 1 — `/fantasy/nfl/my-teams` now carries each league's roster ALREADY joined to its own
  // server-scored board. Computed here for the same reason as the board above: a hardcoded empty
  // map would make "my roster renders" pass on nothing.
  // `any` is honest here rather than lazy: `fixture()` returns parsed JSON, so the league shape is
  // untyped at this boundary and inventing a local interface would be a second, driftable spelling
  // of `SavedLeague`.
  const rostersFor = (ls: any[]) =>
    Object.fromEntries(
      ls.map((l: any) => [
        l.league_id,
        matchRosterToBoard(
          l.imported_roster ?? [],
          buildBoard(FIXTURES.projectionsEntitled().players, l).players,
        ),
      ]),
    )

  if (leagues === "none") {
    return pathname === "/fantasy/leagues"
      ? []
      : { ...base, leagues: [], saved_total: 0, withheld_by_quota: 0, rosters: {} }
  }

  // ⭐ E9.64 — both leagues are the caller's own and both are served; there is no quota story here,
  // so `saved_total` matches and `withheld_by_quota` stays 0 (a lapsed-member notice on this mode
  // would be a second, unrelated behaviour leaking into every My Teams assertion).
  if (leagues === "linked") {
    const pair = linkedLeaguePair()
    return pathname === "/fantasy/leagues"
      ? pair
      : {
          ...base,
          leagues: pair,
          saved_total: pair.length,
          withheld_by_quota: 0,
          rosters: rostersFor(pair),
        }
  }

  if (leagues === "overQuota") {
    // A lapsed subscriber: three saved, one served. The MANAGEMENT list returns all three (they are
    // the user's own configs and must stay deletable); the PERSONALIZATION serve returns one. That
    // asymmetry is the behaviour, so the harness has to reproduce it rather than smoothing it over.
    const all = [
      one,
      { ...one, league_id: "e2e-league-2", name: "Dynasty B", created_at: "2026-08-02T12:00:00Z" },
      { ...one, league_id: "e2e-league-3", name: "Dynasty C", created_at: "2026-08-03T12:00:00Z" },
    ]
    return pathname === "/fantasy/leagues"
      ? all
      : { ...base, leagues: [one], saved_total: 3, withheld_by_quota: 2, rosters: rostersFor([one]) }
  }

  return pathname === "/fantasy/leagues"
    ? [one]
    : { ...base, rosters: rostersFor(base.leagues) }
}

/**
 * Install the API mock and the third-party blocks on a page.
 *
 * Returns a live record of what was asked for — assert `unmatched` is empty in any spec whose
 * conclusion depends on the page having got its data.
 */
/**
 * G100-D1 — the CDN read path.
 *
 * An ANONYMOUS caller no longer calls the API Lambda directly: `lib/api.ts::cdnFetch` fetches the
 * same-origin `/api/public/*` route handler, which Vercel serves from the edge (see that handler's
 * module comment). Those requests do NOT carry `API_PREFIX`, so without this map they would slip
 * past the interceptor entirely — and, because they are same-origin, they would land on the local
 * Next server and be answered by the REAL handler, which would then try to reach the real API. A
 * hermetic suite would silently stop being hermetic.
 *
 * Mapping back to the canonical API path (rather than adding a second fixture key space) is what
 * keeps every existing spec working unchanged: `fail: ["/picks/featured"]` and any `transform`
 * keyed on an API path keep meaning exactly what they meant before, regardless of which transport
 * the page happened to use.
 *
 * ⚠️ COVERAGE NOTE: intercepting here means Playwright answers BEFORE the route handler runs, so
 * the handler's own logic is not exercised by the E2E suite. That is deliberate — its contract
 * (never forwards Authorization, allowlist-only, never caches an empty body) is pinned by
 * `betting_ml/tests/test_g100_d1_cost_guardrails.py`, and its actual payoff is CDN behaviour that
 * no browser test can observe anyway.
 */
const CDN_PREFIX = "/api/public"

function cdnPathToApiPath(pathname: string): string | undefined {
  if (!pathname.startsWith(CDN_PREFIX + "/")) return undefined
  const rest = pathname.slice(CDN_PREFIX.length + 1)
  if (rest === "featured") return "/picks/featured"
  if (rest === "featured-player") return "/fantasy/nfl/featured-player"
  if (rest === "manifest") return "/fantasy/nfl/manifest"
  if (rest === "projections") return "/fantasy/nfl/projections"
  if (rest === "board") return "/fantasy/nfl/board"
  if (rest === "track-record/manifest") return "/fantasy/nfl/track-record/manifest"
  if (/^track-record\/\d{4}$/.test(rest)) return `/fantasy/nfl/${rest}`
  return undefined
}

export async function mockApi(page: Page, options: MockOptions = {}): Promise<ApiMock> {
  // ⭐ DEFAULT FLIPPED FROM "locked" TO "free" (freemium build). The default has to be what an
  // anonymous visitor actually gets, or a new spec that forgets to name a mode silently tests a
  // state no user can reach. Every pre-existing spec names its mode explicitly, so nothing else
  // moves. `entitled` is retained as a distinct name and resolves to the same payloads.
  const entitlement = options.entitlement ?? "free"
  const mock: ApiMock = { requested: [], unmatched: [] }

  /** Answer one intercepted call, given the canonical API path it resolves to. */
  const fulfil = async (route: Route, apiPath: string, search: string) => {
    mock.requested.push(apiPath + search)

    // Held BEFORE anything is answered, so the delay applies whichever branch below serves this
    // path — including the failure branch. See `MockOptions.delay`.
    if (options.delay?.paths.some((p) => apiPath.startsWith(p))) {
      await new Promise((r) => setTimeout(r, options.delay!.ms))
    }

    // ⭐ G100-D0 — SAVING a league, which is a WRITE and therefore invisible to `payloadFor`'s
    // (path, entitlement) map.
    //
    // This exists for one specific assertion. `league_config_completed` is the second clause of the
    // activation definition and the ONLY one with no production evidence yet — it fires on a CREATE
    // and not on an update, and until this handler existed nothing anywhere could drive that path.
    // A funnel step that has never been observed firing is a step the dashboard may well be
    // charting a permanent zero for.
    //
    // Echoing the posted config back (rather than serving a canned league) is what makes the
    // response a real round trip: the editor writes `result.league_id` into its own state and
    // re-reads the config from the response, so a canned body would silently discard what the user
    // typed and the spec would be asserting against a league nobody configured.
    // ⭐ G100-D0-R1 — the post-sign-in writes. Both are `POST`s with no fixture, so without this
    // they would 501 and land in `unmatched`; `/auth/accept-terms` additionally carries the signal
    // the whole signup funnel now keys on, and its THREE modes are not interchangeable (see
    // `MockOptions.termsAcceptance`).
    if (apiPath === "/auth/verify-email") {
      await route.fulfill({ status: 204, body: "" })
      return
    }
    if (apiPath === "/auth/accept-terms") {
      const mode = options.termsAcceptance ?? "existing"
      if (mode === "skew") {
        // The pre-R1 Lambda, verbatim: 204, no body, no `created` key anywhere.
        await route.fulfill({ status: 204, body: "" })
        return
      }
      await route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify({ created: mode === "created" }),
      })
      return
    }

    // ⭐ E9.64 — the review queue. A POST whose answer depends on the league the user clicked, so it
    // cannot live in `payloadFor`'s (path, entitlement) map.
    if (apiPath === "/fantasy/import/sleeper/preview") {
      let leagueId = ""
      try {
        leagueId = JSON.parse(route.request().postData() ?? "{}").league_id ?? ""
      } catch {
        leagueId = ""
      }
      await route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify(importPreviewFor(leagueId)),
      })
      return
    }

    const written = writeResponseFor(apiPath, route.request().method(), route.request().postData())
    if (written !== undefined) {
      await route.fulfill({
        status: 200,
        contentType: "application/json",
        body: JSON.stringify(written),
      })
      return
    }

    if (options.fail?.includes(apiPath)) {
      await route.fulfill({
        status: 503,
        contentType: "application/json",
        body: JSON.stringify({ detail: "e2e: deliberate read failure" }),
      })
      return
    }

    // ⭐ THE HARNESS MODELS THE FORMAT PAYWALL, because a mock that answered 200 for every preset
    // would let a spec "prove" a locked format renders fine — a state no user can reach. One preset
    // is free (`entitlement.FREE_BOARD_CONFIG`/`FREE_BOARD_SIZE`); anything else is a 403.
    // Mirrors `routers/fantasy.py::nfl_board`.
    //
    // ⚠️ "free" ONLY, NOT "not entitled". `"locked"` models the RETIRED E9.56 server, which served
    // every preset with its values removed and had no format tier at all — applying today's paywall
    // there would refuse boards that server answered, and `locked-surfaces.spec.ts` would fail
    // describing a world neither server ever produced. A mock must model ONE server per mode.
    if (apiPath === "/fantasy/nfl/board" && entitlement === "free") {
      const q = new URLSearchParams(search)
      const isFreeBoard = q.get("config") === FREE_BOARD.config && q.get("size") === String(FREE_BOARD.size)
      if (!isFreeBoard) {
        await route.fulfill({
          status: 403,
          contentType: "application/json",
          body: JSON.stringify({ detail: "This league format is part of a Credence membership." }),
        })
        return
      }
    }

    let body =
      personalPayloadFor(apiPath, options.leagues ?? "none") ??
      billingPayloadFor(apiPath, options.subscription ?? "none") ??
      payloadFor(apiPath, entitlement)
    if (body === undefined) {
      mock.unmatched.push(apiPath + search)
      await route.fulfill({
        status: 501,
        contentType: "application/json",
        body: JSON.stringify({ detail: `e2e: no fixture for ${apiPath}` }),
      })
      return
    }
    if (options.transform) body = options.transform(apiPath, body)

    await route.fulfill({
      status: 200,
      contentType: "application/json",
      headers: { "access-control-allow-origin": "*" },
      body: JSON.stringify(body),
    })
  }

  await page.route(`**${API_PREFIX}/**`, async (route: Route, request: Request) => {
    const url = new URL(request.url())
    // Strip the harness prefix so the fixture map is keyed on the API's OWN paths — the same
    // strings that appear in `app/backend/routers/fantasy.py`.
    const apiPath = url.pathname.slice(url.pathname.indexOf(API_PREFIX) + API_PREFIX.length)
    await fulfil(route, apiPath, url.search)
  })

  await page.route(`**${CDN_PREFIX}/**`, async (route: Route, request: Request) => {
    const url = new URL(request.url())
    const apiPath = cdnPathToApiPath(url.pathname)
    if (apiPath === undefined) {
      // An unmapped CDN path is a harness gap, not a pass — surface it the same way an unmatched
      // API path is surfaced rather than letting it reach the real handler.
      mock.unmatched.push(url.pathname + url.search)
      await route.fulfill({
        status: 501,
        contentType: "application/json",
        body: JSON.stringify({ detail: `e2e: unmapped CDN path ${url.pathname}` }),
      })
      return
    }
    await fulfil(route, apiPath, url.search)
  })

  await blockThirdParty(page)
  return mock
}

/**
 * Cut every third-party beacon. Sentry's DSN is hardcoded in `instrumentation-client.ts` and
 * PostHog is proxied through the same-origin `/ingest` rewrite, so without this the suite makes
 * real outbound calls from CI — slow, flaky, and it pollutes production analytics with robot
 * traffic.
 */
export async function blockThirdParty(page: Page) {
  for (const pattern of ["**/ingest/**", "**/*.sentry.io/**", "**/*.i.posthog.com/**"]) {
    await page.route(pattern, (route) => route.abort())
  }
}

/** Collect uncaught page errors so a spec can assert the surface rendered without throwing. */
export function collectPageErrors(page: Page): string[] {
  const errors: string[] = []
  page.on("pageerror", (e) => errors.push(String(e)))
  return errors
}

/**
 * G100-C1 — intercept the analytics wire and record what was CAPTURED.
 *
 * ⭐ WHY THE WIRE AND NOT A STUB. The activation event is a CONTRACT with G100-D0's funnel
 * dashboard: the event NAME and its dimensions are what the dashboard reads. A test that stubbed
 * `posthog.capture` and asserted it was called would pass even if PostHog were never initialised —
 * which is exactly the state this suite was in until G100-C1 armed the token, and is the "asserting
 * a NAME rather than the thing the name refers to" shape the red-proof harness exists to catch.
 * Reading the request body proves the event actually left the page under the name the dashboard
 * expects.
 *
 * ⚠️ Install INSTEAD OF `mockApi`'s `blockThirdParty` for the ingest route — this route is
 * registered after it, and Playwright matches the most recently added handler first.
 *
 * PostHog batches, so a captured event may arrive in a `batch` array or as a single `{event, ...}`;
 * both shapes are flattened here. Bodies can also be compressed or form-encoded depending on
 * transport, so a body this cannot parse is IGNORED rather than throwing — an assertion that an
 * event is ABSENT must therefore never rest on this alone (see `expectCaptured`).
 */
export type CapturedEvent = { event: string; properties: Record<string, unknown> }

export async function captureAnalytics(page: Page): Promise<CapturedEvent[]> {
  const events: CapturedEvent[] = []

  // ⭐⭐ WITHOUT THIS, POSTHOG CAPTURES NOTHING IN PLAYWRIGHT AND EVERY ANALYTICS ASSERTION IS
  // VACUOUS — INCLUDING, AND ESPECIALLY, ONE ASSERTING AN EVENT DID *NOT* FIRE.
  //
  // posthog-js runs a bot filter on every `capture()` (`_is_bot` → `xo`, measured against 1.386.6)
  // and TWO of its clauses catch Playwright. BOTH have to be defeated; clearing either one alone
  // changes nothing, which is what makes this so easy to misdiagnose:
  //
  //   1. `!!navigator.webdriver` — Playwright sets it on every page.
  //   2. `navigator.userAgentData.brands` containing "HeadlessChrome". ⚠️ NOT fixed by overriding
  //      the user-agent STRING via `test.use({ userAgent })`: `userAgentData` is a separate
  //      structured field and keeps reporting the real brand. A UA override therefore LOOKS like
  //      the fix and does nothing — measured.
  //
  // The failure is completely silent: the SDK initialises, POSTs `/flags/`, loads its remote
  // config, and then drops every event including `$pageview`. An empty ingest log is
  // indistinguishable from "the app never called capture()". Two other plausible causes were
  // measured and RULED OUT along the way, so nobody re-chases them: the shipped CSP (`connect-src
  // 'self'` already covers the same-origin `/ingest` path — allowing `blob:` workers changed
  // nothing) and the remote-config stub below.
  //
  // Confined to the harness — no application code knows about it — and `addInitScript` runs before
  // any page script, so the SDK never observes the real values.
  await page.addInitScript(() => {
    Object.defineProperty(navigator, "webdriver", { get: () => false, configurable: true })
    Object.defineProperty(navigator, "userAgentData", {
      get: () => ({
        brands: [
          { brand: "Chromium", version: "140" },
          { brand: "Google Chrome", version: "140" },
        ],
        mobile: false,
        platform: "macOS",
      }),
      configurable: true,
    })
  })

  await page.route("**/ingest/**", async (route: Route, request: Request) => {
    const path = new URL(request.url()).pathname

    // posthog-js will not finish initialising until its REMOTE CONFIG resolves, and it reads that
    // from `window._POSTHOG_REMOTE_CONFIG[token].config` set by this script. An empty body leaves
    // the SDK waiting; every feature is switched OFF here so the harness pulls in no further
    // external dependencies (recordings, surveys, experiments) that it would then have to model.
    if (path.endsWith("/config.js")) {
      const token = POSTHOG_E2E_TOKEN
      const config = {
        supportedCompression: [],
        autocapture_opt_out: true,
        hasFeatureFlags: false,
        sessionRecording: null,
        surveys: false,
        captureDeadClicks: false,
        defaultIdentifiedOnly: false,
        errorTracking: { autocaptureExceptions: false },
      }
      await route.fulfill({
        status: 200,
        contentType: "application/javascript",
        body: `window._POSTHOG_REMOTE_CONFIG = ${JSON.stringify({ [token]: { config, siteApps: [] } })};`,
      })
      return
    }

    // ⚠️ ANY OTHER SCRIPT MUST BE ANSWERED AS JAVASCRIPT, NOT JSON. `/ingest/**` also serves
    // posthog-js's own assets, and a JSON body handed to a `<script>` throws
    // `SyntaxError: Unexpected token ':'` — which surfaced as three uncaught page errors and failed
    // four unrelated assertions running `expectNoPageErrors`, i.e. a harness bug wearing an
    // application defect's clothes.
    if (path.endsWith(".js")) {
      await route.fulfill({ status: 200, contentType: "application/javascript", body: "" })
      return
    }

    if (request.method() === "POST" && /\/(e|i\/v0\/e)\/?$/.test(path)) {
      try {
        const raw = request.postData()
        if (raw) {
          const text = raw.startsWith("data=") ? decodeURIComponent(raw.slice(5)) : raw
          const decoded = /^[A-Za-z0-9+/=_-]+$/.test(text.trim())
            ? Buffer.from(text.trim(), "base64").toString("utf8")
            : text
          const parsed = JSON.parse(decoded)
          for (const item of Array.isArray(parsed) ? parsed : (parsed.batch ?? [parsed])) {
            if (item && typeof item.event === "string") {
              events.push({ event: item.event, properties: item.properties ?? {} })
            }
          }
        }
      } catch {
        /* unparseable transport — never throw from a route handler; see the note above */
      }
    }

    // Answered, never aborted: an aborted request makes posthog-js RETRY, which would multiply a
    // single capture across the retry schedule and break any "fired exactly once" assertion.
    await route.fulfill({
      status: 200,
      contentType: "application/json",
      body: JSON.stringify({ status: 1 }),
    })
  })

  return events
}
