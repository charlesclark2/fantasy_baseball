function payloadFor(pathname: string, entitlement: Entitlement): unknown | undefined {
  const locked = entitlement === "locked"
  if (pathname === "/fantasy/nfl/projections") {
    return locked ? FIXTURES.projectionsLocked() : FIXTURES.projectionsEntitled()
  }
  // 🔒 NF-EPIC 1 — the PAID half of the projection (raw stat line + fpStd/fpHalf).
  //
  // ⚠️ ENTITLED ONLY, and modelling the refusal is the point: falling through to `undefined` makes
  // the harness answer 501/unmatched for a free caller, which is what a spec asserting "a free
  // account cannot obtain the stat line" needs. Serving it to everyone would let that spec pass
  // against a server no caller can reach — the shape this harness's own comments warn about.
  if (pathname === "/fantasy/nfl/projections-full") {
    return entitlement === "entitled" ? FIXTURES.projectionsEntitled() : undefined
  }
  if (pathname === "/subscription/public-pricing") return FIXTURES.publicPricing()
  // ⚠️ THESE TWO USED TO IGNORE `entitlement` ENTIRELY and always serve the locked capture, which
  // was correct while the locked payload was the only anonymous shape. Post-freemium that would
  // make every "free" spec silently assert against the retired redaction — a suite testing a state
  // no user can reach, and passing.
  if (pathname === "/fantasy/nfl/manifest") {
    return locked ? FIXTURES.manifestLocked() : FIXTURES.manifestFree()
  }
  if (pathname === "/fantasy/nfl/board") {
    return locked ? FIXTURES.boardLocked() : FIXTURES.boardFree()
  }
  if (pathname === "/fantasy/nfl/track-record/manifest") return FIXTURES.trackRecordManifest()
  if (/^\/fantasy\/nfl\/track-record\/\d{4}$/.test(pathname)) return FIXTURES.trackRecordSeason()
  if (pathname === "/picks/featured") return FIXTURES.featuredPick()
  if (pathname === "/fantasy/nfl/featured-player") return FIXTURES.featuredFantasyPlayer()
  // ── PLATFORM IMPORT (NF-C0), as far as the LEAGUE LIST ────────────────────────────────────────
  // Deliberately NOT the preview endpoint. The list is where G100-C1's quota boundary is drawn —
  // once an account is at its quota, every league here except the one it already saved is
  // unimportable, and that has to be visible BEFORE the work. Mocking `preview` too would model a
  // flow the free tier is not supposed to be able to reach.
  if (pathname === "/fantasy/import/platforms") return FIXTURES.importPlatforms()
  if (pathname === "/fantasy/import/sleeper/leagues") return FIXTURES.importSleeperLeagues()
  return undefined
}

