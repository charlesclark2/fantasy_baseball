# 2. BOUNDARY (b) — the point is exact; the range is CARRIED, never re-expressed
# ══════════════════════════════════════════════════════════════════════════════════════════════

def test_the_served_band_is_the_payloads_own_band_byte_identical(weekly_players, full_ppr_cfg):
    """⭐ MEASURED AGAINST A LEAGUE THAT MOVES THE POINT HARD. Under six points per reception the
    league point diverges from PPR by a wide margin; if `score_row`'s rescaled interval were
    leaking onto the wire, the band would move with the point. It must not move at all.

    This is the difference between an honest range and a pseudo-band: re-expressing an 80% interval
    under arbitrary scoring needs the per-stat DISTRIBUTIONS (NF-W6c/W6d — staged, no consumer),
    not the per-stat means, and a rescale labelled as this league's would assert a precision the
    substrate does not have."""
    hot = copy.deepcopy(full_ppr_cfg)
    hot["scoring"]["per_stat"]["rec"] = 6.0
    out = _score(weekly_players, _roster_of(weekly_players), hot)
    by_name = {p["name"]: p for p in weekly_players}

    moved = 0
    for row in out["rows"]:
        if row.get("absence") is not None:
            continue
        src = by_name[row["rosterName"]]
        assert row["bandP10"] == src["fpP10"], "the p10 bound was re-expressed, not carried"
        assert row["bandP90"] == src["fpP90"], "the p90 bound was re-expressed, not carried"
        assert row["pprPts"] == src["fpPpr"], "the PPR point the band belongs to was altered"
        if row["leaguePts"] != src["fpPpr"]:
            moved += 1

    assert moved, (
        "no player's league point differed from PPR under 6-point receptions, so this clause "
        "proved nothing — the band could have been rescaled and still matched"
    )


def test_the_rescaled_interval_score_row_returns_is_discarded(
    monkeypatch, weekly_players, full_ppr_cfg
):
    """The scorer's own `p10`/`p90` must reach no field of the response under ANY name.

    Driven by making them unmistakable: if either value appears anywhere in the output, it was
    carried rather than dropped."""
    poison_lo, poison_hi = -12345.5, -54321.5

    real = ls.score_row

    def tagged(row, pos, resolved, stat_field):
        out = dict(real(row, pos, resolved, stat_field))
        out["p10"], out["p90"] = poison_lo, poison_hi
        return out

    monkeypatch.setattr(ls, "score_row", tagged)
    out = _score(weekly_players, _roster_of(weekly_players), full_ppr_cfg)
    blob = json.dumps(out, default=str)
    assert str(poison_lo) not in blob and str(poison_hi) not in blob, (
        "score_row's rescaled interval reached the response; boundary (b) forbids a band that "
        "claims to be in the caller's scoring when nothing re-expressed it"
    )


def test_the_contract_serves_the_ppr_point_the_band_belongs_to():
    """⚠️ A RANGE RENDERED BESIDE A LEAGUE-SCORED POINT WITH NO PPR POINT IN SIGHT IS A FALSE CLAIM
    — it reads as that point's range, and it is not. So `pprPts` is not an optional extra: it is
    what makes the carried band honest, and the contract must declare it beside the band."""
    fields = set(C.NflWeeklyLeagueRow.model_fields)
    assert {"leaguePts", "pprPts", "bandP10", "bandP90"} <= fields
    note = C.SCORING_BASIS_NOTE.lower()
    assert "ppr" in note and "range" in note, "the scope note does not state what the range is in"


