"""NF-WK-MT1 — the league-scored WEEKLY line, and the three boundaries that keep it honest.

The paid question the weekly stack exists to answer is "what does MY roster do this week, in MY
league's scoring". Answering it needs no new scoring code and no new distribution: the champion's
component head is already served under the field names `league_scoring` reads, so the ONE server
scorer runs over a weekly row verbatim. What this file pins is the set of things that are TRUE only
because someone chose them, and which nothing else would notice going wrong:

  1. NO FOURTH SCORER. Proven by SUBSTITUTION — `league_scoring.score_row` is replaced with a
     sentinel and the sentinel must come out the other end. A docstring claiming reuse cannot
     satisfy that (INC-38), and neither can an import nothing invokes (NF-C0e's wired-≠-invoked).
     Backed by an AST scan: the adapter carries no numeric literal at all, so it cannot be holding
     a scoring weight of its own.

  2. THE POINT IS EXACT AND THE RANGE IS NOT RE-EXPRESSED. `score_row` returns an interval by
     rescaling the payload's bounds by the ratio the point moved; that value is DISCARDED, and the
     band on the wire is the payload's own, byte-identical. Proven with a league whose scoring
     moves the point hard — if the rescale were leaking through, the band would move with it.

  3. THE TWO PARITY QUESTIONS ARE DIFFERENT QUESTIONS, and each clause says which it asks:
       (a) GATED — our scorer, under the shipped full-PPR preset, against an INDEPENDENT full-PPR
           implementation over the SAME component line. Must agree to float tolerance.
       (b) DIAGNOSTIC, NEVER GATED — the component line against the POINTS HEAD. Those are two
           independent heads of one model, and NF-C6-PH2 measured the gap (mean SIGNED -0.7709,
           median |d| 0.6016, p95 3.7101, max 7.9200, n=503 staged rows, 2026-09-05). Asserting
           they agree would be asserting something known to be false; this file pins that nothing
           does, and that the two numbers stay DISTINCT declared fields on the wire.

⭐ THE ORACLE IN (3a) IS NOT A RESTATEMENT OF THE CODE. It is
`run_nf_c6_ph2_promotion_review.component_coherence`, written by NF-C6-PH2 for a different purpose
before this story existed, and it is USED rather than copied: we overwrite `fpPpr` with our own
output and require the coherence it measures to be exactly zero. A test that recomputed the formula
beside the implementation would be the NF-C0e "reads the value back under the key the code wrote"
shape and would stay green through a wrong stat key — the defect it most needs to catch.

RED-PROVEN: `uv run python betting_ml/tests/nf_wk_mt1_red_proof.py`. Every clause naming a specific
rule has its OWN fixture in which every other clause is satisfied (NF-D17 §7): a fixture that trips
two clauses tests neither, because the first refusal hides the second.

🗓️ FIXTURE TRIPWIRE (inherited, NF-WK-FE1 finding 6 / E9.64b). The weekly fixtures are GENERATED by
the shipping writer because nothing weekly has published yet, so they can only confirm the shape we
already assumed. On the first real publish they are retired and re-captured RAW, and every clause
here re-runs against the captured ones. The clauses are written to survive that: none hardcodes a
player, a point or a row count that a real payload would change — the one count that IS pinned
(`test_the_parity_clause_is_not_vacuous`) is pinned as a FLOOR, so more real rows strengthen it.

Pure/offline (fast gate): committed fixtures, source files and pure functions only. No DuckDB/S3/
network and no `pipeline` import (E11.23). The two heavy imports — the oracle and the league presets
— are LAZY, inside the clauses that use them, so per-worker collection pays nothing for them.
"""
