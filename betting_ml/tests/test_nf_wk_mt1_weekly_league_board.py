# Everything above reasons about the route from its signature, its dependency chain and its path.
# None of that proves a request reaches the adapter and comes back shaped. These clauses drive the
# REAL ASGI app.
#
# Raw ASGI rather than starlette's `TestClient`, for the reason E9.56's suite documents: TestClient
# needs `httpx` (absent here) and cannot set the `aws.event` scope key Mangum uses to carry the API
# Gateway authorizer context — the one thing separating a real account from a forged token.

_LEAGUE_ID = "lg-mt1"


def _call(path: str, query: str = "", *, aws_event: dict | None = None):
    """Drive the real app. Returns `(status, parsed_body_or_raw_bytes)`."""
    import anyio

    from app.backend.main import app

    out: dict = {}
    parts: list[bytes] = []

    async def run():
        scope = {
            "type": "http",
            "asgi": {"version": "3.0", "spec_version": "2.1"},
            "http_version": "1.1",
            "method": "GET",
            "scheme": "https",
            "path": path,
            "raw_path": path.encode(),
            "query_string": query.encode(),
            "root_path": "",
            "headers": [(b"host", b"testserver"), (b"content-type", b"application/json")],
            "client": ("test", 1),
            "server": ("testserver", 443),
        }
        if aws_event is not None:
            scope["aws.event"] = aws_event

        async def receive():
            return {"type": "http.request", "body": b"", "more_body": False}

        async def send(message):
            if message["type"] == "http.response.start":
                out["status"] = message["status"]
            elif message["type"] == "http.response.body":
                parts.append(message.get("body", b""))

        await app(scope, receive, send)

    anyio.run(run)
    payload = b"".join(parts)
    try:
        return out["status"], json.loads(payload)
    except Exception:  # noqa: BLE001 — a 401 body may not be JSON, which is a valid outcome
        return out["status"], payload


def _event(groups: str = "[]", sub: str = "user-1"):
    """The authorizer context as Mangum delivers it. ⚠️ `cognito:groups` is BRACKETED and
    SPACE-separated even for one group — NOT comma-separated (G100-C0-MFA measured it); a fixture
    written in the comma form would restate the parser's own assumption and pass on nothing."""
    return {
        "requestContext": {
            "authorizer": {"jwt": {"claims": {"sub": sub, "cognito:groups": groups}}}
        }
    }


