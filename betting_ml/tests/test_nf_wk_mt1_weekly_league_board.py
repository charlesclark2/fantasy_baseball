# 5. COVERAGE — "contributed nothing" and "is not in this number" are different facts
# ══════════════════════════════════════════════════════════════════════════════════════════════

def test_a_league_term_the_weekly_line_cannot_express_is_reported_captured(
    weekly_players, full_ppr_cfg
):
    """⭐ AN ORDINARY FULL-PPR LEAGUE HAS REAL WEIGHTS THIS WEEK'S LINE CANNOT EXPRESS. The champion
    emits eleven components; the preset scores `fumbles_lost` and `two_pt` too, plus every kicker
    and defence term. Those must resolve CAPTURED — named in the report — rather than silently
    zeroed behind an "applied" label.

    ⚠️ The APPLIED set is asserted EXACTLY, not as a subset: a term drifting from captured to
    applied is precisely how a number starts quietly including something it cannot compute."""
    out = _score(weekly_players, _roster_of(weekly_players), full_ppr_cfg)
    terms = out["coverage"]["terms"]
    applied = {t["key"] for t in terms if t["verdict"] == "applied"}
    captured = {t["key"] for t in terms if t["verdict"] == "captured"}

    assert applied == {
        "pass_yds", "pass_td", "pass_int", "rush_yds", "rush_td", "rec", "rec_yds", "rec_td",
    }
    assert {"fumbles_lost", "two_pt"} <= captured, (
        "a full-PPR league's fumble and two-point scoring is absent from the weekly component "
        "line; reporting it as applied would claim a number we did not compute"
    )
    assert any(k.startswith("fg_made") or k.startswith("def_") for k in captured)


