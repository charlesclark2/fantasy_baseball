# 3. THE PARITY CLAUSE — and the OTHER comparison, which is a diagnostic and not a gate
# ══════════════════════════════════════════════════════════════════════════════════════════════

def _oracle_diff(players: list[dict], rows: list[dict]) -> dict:
    """Overwrite `fpPpr` with OUR scorer's output and ask NF-C6-PH2's independent implementation
    how far apart they are. Zero means our wiring reproduces full-PPR exactly."""
    from quant_sports_intel_models.football.nfl.fantasy.run_nf_c6_ph2_promotion_review import (
        component_coherence,
    )

    probe = copy.deepcopy({"players": players})
    by_name = {r["rosterName"]: r for r in rows}
    for p in probe["players"]:
        hit = by_name.get(p.get("name"))
        if hit and hit.get("leaguePts") is not None:
            p["fpPpr"] = hit["leaguePts"]
    return component_coherence(probe)


def test_the_server_scorer_reproduces_full_ppr_over_the_weekly_line(
    weekly_players, full_ppr_cfg
):
    """⭐ THE GATED COMPARISON: OUR SCORER vs AN INDEPENDENT FULL-PPR IMPLEMENTATION, over the SAME
    component line. NOT the component sum against the points head — that is a different question
    with a known non-zero answer, and it is the clause below.

    What it catches is the whole wrong-key family (NF-C0e): a component mapped to the wrong stat
    key, a term silently dropped, a weight misapplied. All of those leave every other test green,
    because an unrecognized key passes through as `captured` with no error."""
    out = _score(weekly_players, _roster_of(weekly_players), full_ppr_cfg)
    res = _oracle_diff(weekly_players, out["rows"])

    assert res["evaluable"] is True, f"the oracle could not score anything: {res}"
    assert res["max_abs_diff"] == 0.0, (
        f"our full-PPR scoring of the weekly component line disagrees with an independent "
        f"implementation of the same formula over the same line: {res}"
    )
    assert res["mean_signed_diff"] == 0.0


def test_the_parity_clause_is_not_vacuous(weekly_players, full_ppr_cfg):
    """A comparison that scored NO rows would pass the clause above while proving nothing
    (NF1.7 (a)). The oracle skips byes and rows with no component line, so the count it actually
    reached is asserted as a FLOOR — a real captured payload will raise it, never lower it."""
    out = _score(weekly_players, _roster_of(weekly_players), full_ppr_cfg)
    res = _oracle_diff(weekly_players, out["rows"])
    assert res.get("n", 0) >= 5, (
        f"only {res.get('n')} rows reached the parity comparison; below that it is not measuring "
        "the field map it exists to police"
    )


def test_the_component_line_is_never_asserted_to_equal_the_points_head():
    """⭐ THE DIAGNOSTIC, AND WHY IT MUST NOT BECOME A GATE. The weekly point and the weekly
    component line come from two INDEPENDENT heads of one model; NF-C6-PH2 measured the gap at mean
    SIGNED -0.7709 (the components score BELOW the head), median |d| 0.6016, p95 3.7101, max
    7.9200, over n=503 staged rows on 2026-09-05. Asserting equality would be asserting something
    already measured false, and a surface that presented one as a correction of the other would be
    making a claim the model does not support.

    ⛔ AND THE DIRECTION IS RECORDED BECAUSE IT IS COUNTER-INTUITIVE: a disclosure phrased as "the
    components may exceed the total" is BACKWARDS. The PM adopted that warning verbatim
    (2026-09-14, the NF-WK-FE1 disposition) after the same figures were mislabelled once and
    propagated by copy.

    So the two stay DISTINCT declared fields, and nothing here folds one into the other."""
    fields = C.NflWeeklyLeagueRow.model_fields
    assert "leaguePts" in fields and "pprPts" in fields
    src = ADAPTER.read_text()
    assert "leaguePts" in src and "pprPts" in src
    # The adapter must not reconcile them — no assignment of one from the other.
    assert 'row["pprPts"] = row["leaguePts"]' not in src
    assert 'row["leaguePts"] = row["pprPts"]' not in src


