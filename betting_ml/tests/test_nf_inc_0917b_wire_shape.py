def _bare_model_validate_lines(path: Path) -> list[int]:
    """Line numbers where `…model_validate(…)` is an EXPRESSION STATEMENT — validated, discarded.

    ⭐ AST, NOT GREP, and the difference is not pedantry here: this file's own comments quote the
    defective form several times to explain it, and a substring scan would fire on the explanation
    while a deleted assignment went unnoticed. The parser only sees code.
    """
    import ast

    tree = ast.parse(path.read_text())
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Expr) or not isinstance(node.value, ast.Call):
            continue
        fn = node.value.func
        if isinstance(fn, ast.Attribute) and fn.attr == "model_validate":
            out.append(node.lineno)
    return out


def test_the_ast_scan_can_actually_see_a_discarded_validation():
    """NF1.7(a) — if the scanner cannot find the pattern in a sample that certainly contains it,
    the assertion below passes on everything."""
    import ast
    import tempfile

    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as fh:
        fh.write("import m\ndef f(x):\n    m.Model.model_validate(x)\n    return x\n")
        probe = Path(fh.name)
    try:
        assert _bare_model_validate_lines(probe) == [3], "the scanner is blind to its own subject"
    finally:
        probe.unlink()
    assert ast.parse(_RUNNER.read_text()), "the runner no longer parses"


def test_the_weekly_builder_never_validates_and_discards():
    """⛔⛔ THE DEFECT CLASS, BANNED IN THE FILE IT SHIPPED FROM.

    A bare `Model.model_validate(blob)` statement asserts something about a value nobody keeps. On
    a contract with DEFAULTED fields that is not merely useless — it is actively misleading, because
    it reads like a gate and cannot fail on the one thing that actually went wrong. Every
    validation in this runner must bind its result and that result must be what gets written.
    """
    bare = _bare_model_validate_lines(_RUNNER)
    assert bare == [], (
        f"{_RUNNER.name} validates and discards at line(s) {bare} — the NF-INC-0917 shape. "
        "Bind the result and write THAT, or the default lands on an object nobody ships."
    )


def test_the_manifest_route_carries_both_halves_of_the_fix():
    """⭐ BOTH, AND THE REDUNDANCY IS DELIBERATE — which is why it needs its own guard.

    The response model and the explicit coercion protect against different failures: the model
    enforces the shape on every return path and documents it, the coercion fills the contract from
    a blob written before the builder was fixed. Because each ALONE is sufficient to keep the wire
    complete today, no behavioural test can notice one of them being deleted — the other silently
    covers for it. So the structural claim is made here, where a deletion is visible.
    """
    import ast

    tree = ast.parse(_ROUTER.read_text())
    fn = next((n for n in ast.walk(tree)
               if isinstance(n, ast.FunctionDef) and n.name == "nfl_weekly_manifest"), None)
    assert fn is not None, "the weekly manifest handler has been renamed — this guard is vacuous"

    declared = {
        kw.arg
        for dec in fn.decorator_list if isinstance(dec, ast.Call)
        for kw in dec.keywords
    }
    assert "response_model" in declared, (
        "the weekly manifest route lost its response_model — it is a pass-through of the S3 blob "
        "again, which is the state the outage was served in"
    )
    coerces = any(
        isinstance(n, ast.Attribute) and n.attr == "model_validate"
        for r in ast.walk(fn) if isinstance(r, ast.Return)
        for n in ast.walk(r)
    )
    assert coerces, (
        "the handler returns without coercing through the contract — a blob already sitting in S3 "
        "would reach the wire with whatever fields it happens to carry"
    )
