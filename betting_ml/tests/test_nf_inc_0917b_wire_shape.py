def _degenerate(blob: dict, *keys: str) -> dict:
    """A real payload with keys REMOVED — the only fixture shape that can reach the broken branch.

    ⛔ Deliberately not a second hand-written fixture: one written beside the shipping writer drifts
    from it silently, and then the guard tests a payload nothing produces (NF-C0e).
    """
    out = json.loads(json.dumps(blob))
    for k in keys:
        out.pop(k, None)
    return out


